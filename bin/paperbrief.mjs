#!/usr/bin/env node
// paperbrief — arXiv topic to research digest in one command.
// Zero dependencies, Node 18+, no API key (arXiv API is open).
// Usage:
//   node bin/paperbrief.mjs search <query...> [--n=10]
//   node bin/paperbrief.mjs brief <query...> [--n=10] [--out=file.md]
import { writeFileSync } from "node:fs";

const API = "https://export.arxiv.org/api/query";

function field(block, tag) {
  const m = block.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`));
  return m ? m[1].replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim() : "";
}

function parseAtom(xml) {
  const entries = [];
  for (const [, block] of xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)) {
    const authors = [...block.matchAll(/<author>\s*<name>([\s\S]*?)<\/name>/g)].map((a) => a[1].trim());
    entries.push({
      id: field(block, "id"),
      title: field(block, "title"),
      summary: field(block, "summary"),
      authors,
      published: field(block, "published").slice(0, 10),
      updated: field(block, "updated").slice(0, 10),
      pdf: (block.match(/<link[^>]*title="pdf"[^>]*href="([^"]+)"/) || [])[1] || "",
    });
  }
  return entries;
}

async function search(query, n) {
  const url = `${API}?search_query=all:${encodeURIComponent(query)}&start=0&max_results=${n}&sortBy=relevance&sortOrder=descending`;
  const res = await fetch(url, { headers: { "User-Agent": "paperbrief/0.1.0" } });
  if (!res.ok) throw new Error(`arXiv fetch failed (${res.status}) — retry in a minute (rate limited to 1 req / 3s)`);
  return parseAtom(await res.text());
}

function digest(query, papers) {
  const lines = [`# Paperbrief: ${query}`, "", `_${papers.length} most relevant arXiv papers, ${new Date().toISOString().slice(0, 10)}_`, ""];
  papers.forEach((p, i) => {
    lines.push(`## ${i + 1}. ${p.title}`, "");
    lines.push(`- **Authors:** ${p.authors.slice(0, 5).join(", ")}${p.authors.length > 5 ? " et al." : ""}`);
    lines.push(`- **Published:** ${p.published} · **arXiv:** ${p.id.split("/abs/")[1] || p.id}`);
    lines.push(`- **Links:** [abs](${p.id})${p.pdf ? ` · [pdf](${p.pdf})` : ""}`);
    lines.push(`- **TL;DR:** ${p.summary.split(". ").slice(0, 2).join(". ")}${p.summary.includes(".") ? "." : ""}`, "");
  });
  lines.push("---", "_Digested from abstracts only — read the PDFs before citing. Generated by paperbrief._");
  return lines.join("\n");
}

const [cmd, ...rest] = process.argv.slice(2);
const flags = {};
const queryParts = [];
for (let i = 0; i < rest.length; i++) {
  const a = rest[i];
  if (a.startsWith("--")) {
    const eq = a.indexOf("=");
    if (eq === -1) {
      const key = a.slice(2);
      if (rest[i + 1] && !rest[i + 1].startsWith("--")) flags[key] = rest[++i]; // --out file
      else flags[key] = "true";
    } else flags[a.slice(2, eq)] = a.slice(eq + 1); // --out=file
  } else queryParts.push(a);
}
const query = queryParts.join(" ");
const n = Math.min(Number(flags.n) || 8, 30);
if (!query) {
  console.error("paperbrief: usage: search <query> [--n=8] | brief <query> [--n=8] [--out=file.md]");
  process.exit(1);
}
try {
  const papers = await search(query, n);
  if (papers.length === 0) {
    console.error("paperbrief: no papers found — try broader terms");
    process.exit(1);
  }
  if (cmd === "search") {
    for (const p of papers) console.log(`- ${p.title} (${p.published}) ${p.id}`);
  } else if (cmd === "brief") {
    const out = digest(query, papers);
    if (flags.out) { writeFileSync(flags.out, out); console.log(`paperbrief: wrote ${flags.out} (${papers.length} papers)`); }
    else console.log(out);
  } else {
    console.error("paperbrief: unknown command (search|brief)");
    process.exit(1);
  }
} catch (e) {
  console.error("paperbrief: " + (e?.message ?? e));
  process.exit(1);
}
